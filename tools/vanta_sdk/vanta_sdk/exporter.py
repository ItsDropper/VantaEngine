"""Deterministic Wavefront OBJ/MTL export and build metadata."""
from __future__ import annotations
import hashlib
import json
import os
from pathlib import Path
import re
import tempfile
from .model import Model

def _atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent, text=True)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\\n") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    except BaseException:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass
        raise

def export_obj(model: Model, output_dir: Path, source_script: Path | None = None) -> dict:
    model.validate()
    output_dir = Path(output_dir)
    stem = re.sub(r"[^A-Za-z0-9_.-]+", "_", model.name).strip("._")
    if not stem:
        raise ValueError("model name does not produce a valid output filename")
    obj_path, mtl_path = output_dir/f"{stem}.obj", output_dir/f"{stem}.mtl"
    metadata_path = output_dir/f"{stem}.vanta-model.json"
    obj = ["# Generated by VantaEngine Python SDK", f"mtllib {mtl_path.name}", ""]
    offset, triangles = 1, 0
    for mesh in model.meshes:
        obj.extend((f"o {mesh.name}", f"usemtl {mesh.material}"))
        obj.extend(f"v {x:.9g} {y:.9g} {z:.9g}" for x,y,z in mesh.vertices)
        for face in mesh.faces:
            obj.append("f " + " ".join(str(offset+i) for i in face))
            triangles += len(face)-2
        offset += len(mesh.vertices)
        obj.append("")
    obj_content = "\n".join(obj) + "\n"
    mtl = ["# Generated by VantaEngine Python SDK"]
    for material in model.materials.values():
        r,g,b = material.base_color
        mtl.extend(("", f"newmtl {material.name}", f"Kd {r:.9g} {g:.9g} {b:.9g}",
                    f"Pr {material.roughness:.9g}", f"Pm {material.metallic:.9g}"))
    mtl_content = "\n".join(mtl) + "\n"
    _atomic_write(obj_path, obj_content)
    _atomic_write(mtl_path, mtl_content)
    source_hash = hashlib.sha256(Path(source_script).read_bytes()).hexdigest() if source_script else None
    metadata = {
        "schema_version": 1, "format": "wavefront_obj", "model": model.name,
        "source_sha256": source_hash,
        "geometry": {"mesh_count": len(model.meshes),
                     "vertex_count": sum(len(mesh.vertices) for mesh in model.meshes),
                     "triangle_count": triangles, "material_count": len(model.materials)},
        "files": {obj_path.name: hashlib.sha256(obj_content.encode()).hexdigest(),
                  mtl_path.name: hashlib.sha256(mtl_content.encode()).hexdigest()},
    }
    _atomic_write(metadata_path, json.dumps(metadata, indent=2, sort_keys=True)+"\n")
    return metadata
